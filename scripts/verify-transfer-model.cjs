const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const compiled = ts.transpileModule(fs.readFileSync('src/features/transfer/model.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const modelModule = new Module('transfer-model');
modelModule._compile(compiled, 'transfer-model.cjs');
const { transferReducer: reduce, initialTransferState, DEMO_DRAFT, approvalCount, draftError } = modelModule.exports;
let state = reduce(initialTransferState, { type: 'create', draft: DEMO_DRAFT });
const id = state.request.id;
assert.equal(reduce(state, { type: 'send', id, verified: true, signatureLength: 0 }), state);
assert.equal(reduce(state, { type: 'send', id, verified: false, signatureLength: 100 }), state);
state = reduce(state, { type: 'send', id, verified: true, signatureLength: 100 });
assert.equal(approvalCount(state.request), 1);
assert.equal(reduce(state, { type: 'create', draft: { ...DEMO_DRAFT, amount: '1' } }), state);
assert.equal(reduce(state, { type: 'complete', id, processedAt: 'test' }), state);
assert.equal(reduce(state, { type: 'approve', id, member: 'member1', signatureLength: 0 }), state);
for (const member of ['member1', 'member2', 'member3']) {
  state = reduce(state, { type: 'approve', id, member, signatureLength: 100 });
  assert.equal(state.balance, 3200000);
  assert.equal(reduce(state, { type: 'approve', id, member, signatureLength: 100 }), state);
}
assert.equal(state.request.status, 'all_approved');
assert.equal(approvalCount(state.request), 4);
state = reduce(state, { type: 'complete', id, processedAt: '2026-10-06T00:00:00Z' });
assert.equal(state.balance, 2400000);
assert.equal(state.request.status, 'completed');
assert.equal(reduce(state, { type: 'complete', id, processedAt: 'test' }), state);
state = reduce(state, { type: 'reset' });
assert.equal(state.balance, 3200000);
state = reduce(state, { type: 'create', draft: DEMO_DRAFT });
const newId = state.request.id;
assert.notEqual(newId, id);
state = reduce(state, { type: 'send', id: newId, verified: true, signatureLength: 100 });
state = reduce(state, { type: 'reject', id: newId, member: 'member2' });
assert.equal(state.request.status, 'rejected');
assert.equal(state.balance, 3200000);
assert.equal(reduce(state, { type: 'approve', id: newId, member: 'member1', signatureLength: 100 }), state);
assert.equal(reduce(state, { type: 'complete', id: newId, processedAt: 'test' }), state);
state = reduce(state, { type: 'create', draft: DEMO_DRAFT });
const cancelledId = state.request.id;
state = reduce(state, { type: 'send', id: cancelledId, verified: true, signatureLength: 100 });
state = reduce(state, { type: 'cancel', id: cancelledId });
assert.equal(state.balance, 3200000);
state = reduce(state, { type: 'create', draft: { ...DEMO_DRAFT, amount: '600000' } });
assert.equal(state.request.amount, 600000);
assert.equal(reduce(state, { type: 'approve', id: cancelledId, member: 'member1', signatureLength: 100 }), state);
assert(draftError({ ...DEMO_DRAFT, amount: '3200001' }, 3200000));
console.log('PASS: unanimous approvals, rejection, cancellation, amount validation, blank signatures, identity check, duplicate actions, stale requests, one balance deduction, demo reset');
